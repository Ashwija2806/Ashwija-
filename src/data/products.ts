function buildStockMap(sizes: string[], outOfStockSize?: string): Record<string, number> {
  const stock: Record<string, number> = {};
  sizes.forEach((size, idx) => {
    if (outOfStockSize && size === outOfStockSize) {
      stock[size] = 0;
    } else {
      stock[size] = 6 + ((idx * 3) % 14);
    }
  });
  return stock;
}

function buildReviewsForProduct(seed: SeedItem, index: number): ProductReview[] {
  const baseReviews = SAMPLE_REVIEWS.map((r, rIdx) => ({
    ...r,
    id: `${seed.id}-rev-${rIdx}`,
    rating: rIdx === 0 ? 5 : Math.max(3, Math.round(seed.rating)),
  }));
  if (index % 2 === 0) {
    return baseReviews;
  }
  return baseReviews.slice(0, 2);
}

